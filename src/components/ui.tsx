export function Button({
  children,
  icon,
  secondary = false,
  onClick,
  type = "button",
  disabled = false,
  ariaLabel,
  ariaPressed,
  title,
}: {
  children: ReactNode;
  icon?: IconName;
  secondary?: boolean;
  onClick?: () => void;
  type?: "button" | "submit";
  disabled?: boolean;
  ariaLabel?: string;
  ariaPressed?: boolean;
  title?: string;
}) {
  return (
    <button type={type} disabled={disabled} onClick={onClick}
      aria-label={ariaLabel} aria-pressed={ariaPressed} title={title}
      className={`btn ${secondary ? "btn-secondary" : ""}`}
    >
      {icon && <Icon name={icon} size={16} />} {children}
    </button>
  );
}
